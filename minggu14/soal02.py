def konversi(): 
    list1 = ['Cheila', 'Virjie', 'Alicia', 'Valine'] 
    print('\n1. List awal: ', list1) 
    listSet = set(list1) 
    print('List ke Set: ', listSet) 
    SetList = list(list1) 
    print('Set ke List: ', SetList) 

    tuple1 = ('Cheila', 'Virjie', 'Alicia', 'Valine') 
    print('\n2. Tuple Awal: ', tuple1) 
    tupleSet = set(tuple1) 
    print('Tuple ke Set: ', tupleSet) 
    setTuple = tuple(tuple1) 
    print('Set ke Tuple: ', setTuple) 
konversi()